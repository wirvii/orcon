func TestRunFilesAndMsg(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	write := func(name, content string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(name), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(name, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("docs/clean.md", "mneme tracks specs; OpenAPI is the contract.\n")
	write("docs/dirty.md", "written with Claude\n")
	write("internal/ai/provider.go", "// provider for Anthropic\n")
	write("internal/ai/trailer.go", "// Co-Authored-By: Claude <noreply@anthropic.com>\n")
	write(".claude/notes.md", "Claude lives here\n")
	write("CLAUDE.md", "Claude instructions\n")
	write("logo.bin", "\x00Claude\x00")
	write(".provenance-allow", "internal/ai/**  # product AI feature\n")

	var out, errOut bytes.Buffer
	args := []string{
		"files", "docs/clean.md", ".claude/notes.md", "CLAUDE.md", "logo.bin", "internal/ai/provider.go",
	}
	if code := run(context.Background(), args, &out, &errOut); code != 0 {
		t.Fatalf("clean files = %d\nstdout: %s\nstderr: %s", code, out.String(), errOut.String())
	}

	out.Reset()
	errOut.Reset()
	code := run(context.Background(), []string{"files", "docs/dirty.md", "internal/ai/trailer.go"}, &out, &errOut)
	if code != 1 {
		t.Fatalf("dirty files = %d, want 1\nstdout: %s", code, out.String())
	}
	for _, wantSub := range []string{"docs/dirty.md:", "internal/ai/trailer.go:", "class A"} {
		if !strings.Contains(out.String(), wantSub) {
			t.Errorf("stdout missing %q:\n%s", wantSub, out.String())
		}
	}
	if !strings.Contains(errOut.String(), "remove AI attribution") {
		t.Errorf("stderr missing the fix hint: %s", errOut.String())
	}

	write("good-msg", "fix(engine): honor cancellation\n\nValidated with mneme.\n")
	write("bad-msg", "feat: add retries\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n")
	if code := run(context.Background(), []string{"msg", "good-msg"}, &out, &errOut); code != 0 {
		t.Fatalf("good msg = %d", code)
	}
	if code := run(context.Background(), []string{"msg", "bad-msg"}, &out, &errOut); code != 1 {
		t.Fatalf("bad msg = %d, want 1", code)
	}
	if code := run(context.Background(), []string{"msg"}, &out, &errOut); code != 2 {
		t.Fatalf("msg without a file = %d, want 2", code)
	}
	if code := run(context.Background(), nil, &out, &errOut); code != 2 {
		t.Fatalf("no arguments = %d, want 2", code)
	}
	write(".provenance-allow", "internal/ai/**\n")
	if code := run(context.Background(), []string{"files", "docs/clean.md"}, &out, &errOut); code != 2 {
		t.Fatalf("allow entry without a reason = %d, want 2", code)
	}
}

func TestRunRange(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git is not installed")
	}
	dir := t.TempDir()
	t.Chdir(dir)
	t.Setenv("GIT_CONFIG_GLOBAL", os.DevNull)
	t.Setenv("GIT_CONFIG_SYSTEM", os.DevNull)
	git := func(args ...string) string {
		t.Helper()
		cmd := exec.CommandContext(t.Context(), "git", append([]string{"-c", "user.name=T", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false"}, args...)...)
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
		return strings.TrimSpace(string(out))
	}
	commit := func(msg string) string {
		t.Helper()
		if err := os.WriteFile("f.txt", []byte(msg), 0o600); err != nil {
			t.Fatal(err)
		}
		git("add", "f.txt")
		git("commit", "-q", "-m", msg)
		return git("rev-parse", "HEAD")
	}
	git("init", "-q")
	base := commit("chore: start")
	commit("fix(engine): honor cancellation")
	good := commit("docs: record SPEC-008 decisions in mneme")

	var out, errOut bytes.Buffer
	run := func(args ...string) int {
		out.Reset()
		errOut.Reset()
		return run(context.Background(), args, &out, &errOut)
	}
	if code := run("range", base, good); code != 0 {
		t.Fatalf("clean range = %d\n%s%s", code, out.String(), errOut.String())
	}

	bad := commit("feat: add retries\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
	if code := run("range", base, bad); code != 1 {
		t.Fatalf("range with a bad commit = %d, want 1", code)
	}
	if !strings.Contains(out.String(), "commit "+bad[:12]) {
		t.Fatalf("stdout does not name the commit %s:\n%s", bad[:12], out.String())
	}
	// A range that stops before the bad commit stays clean.
	if code := run("range", base, good); code != 0 {
		t.Fatalf("clean range after adding a bad commit = %d", code)
	}

	// New-branch push: the zero base checks only the head commit.
	if code := run("range", zeroSHA, good); code != 0 {
		t.Fatalf("zero base on a clean head = %d", code)
	}
	if code := run("range", zeroSHA, bad); code != 1 {
		t.Fatalf("zero base on a bad head = %d, want 1", code)
	}

	// Pull request title and body: flags may follow the positionals.
	body := filepath.Join(dir, "body.md")
	if err := os.WriteFile(body, []byte("Adds the Anthropic provider.\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if code := run("range", base, good, "--pr-title", "feat(llm): add Anthropic provider", "--pr-body-file", body); code != 0 {
		t.Fatalf("product-scope title and body = %d\n%s", code, out.String())
	}
	if code := run("range", base, good, "--pr-title", "feat(engine): add retries", "--pr-body-file", body); code != 1 {
		t.Fatalf("non-product title with vendor body = %d, want 1", code)
	}
	if code := run("range", "--pr-title", "feat: x", base, good); code != 0 {
		t.Fatalf("flags before positionals = %d", code)
	}
	if code := run("range", base); code != 2 {
		t.Fatalf("range with one ref = %d, want 2", code)
	}
}
