type want struct {
	class Class
	line  int
}

func classes(fs []Finding) []want {
	out := make([]want, 0, len(fs))
	for _, f := range fs {
		out = append(out, want{f.Class, f.Line})
	}
	return out
}

func TestScan(t *testing.T) {
	tests := []struct {
		name string
		kind Kind
		opts Options
		text string
		want []want
	}{
		// Never flagged: mneme in every form (D-O4).
		{name: "mneme lower", kind: KindFile, text: "Orcon uses mneme for specs.\n"},
		{name: "mneme capitalized", kind: KindFile, text: "Mneme keeps the backlog.\n"},
		{name: "mneme command", kind: KindFile, text: "run `mneme skills lint orcon-go` after editing\n"},
		{name: "mneme directory in prose", kind: KindFile, text: "specs live under .mneme/ in the repository\n"},
		{name: "mneme in commit", kind: KindCommit, text: "docs: record SPEC-008 decisions in mneme\n\nValidated with mneme skills lint orcon-go.\n"},
		{name: "common words are not flagged", kind: KindFile, text: "the agent uses a cursor; the AI feature is an assistant of sorts\n"},

		// OpenAPI is not OpenAI.
		{name: "OpenAPI does not match OpenAI", kind: KindFile, text: "OpenAPI 3.1 is the source of truth; see openapi.yaml\n"},
		{name: "OpenAI matches", kind: KindFile, text: "uses OpenAI models\n", want: []want{{ClassB, 1}}},

		// Class B in files.
		{name: "class B terms", kind: KindFile, text: "Claude\nClaude Code\nAnthropic\nCodex\nChatGPT\nGitHub Copilot\n", want: []want{
			{ClassB, 1}, {ClassB, 2}, {ClassB, 3}, {ClassB, 4}, {ClassB, 5}, {ClassB, 6},
		}},
		{name: "class B is case insensitive", kind: KindFile, text: "CLAUDE and anthropic\n", want: []want{{ClassB, 1}, {ClassB, 1}}},
		{name: "class B needs a word boundary", kind: KindFile, text: "claudette and codexes are different words\n"},
		{name: "class B allowed in product paths", kind: KindFile, opts: Options{AllowClassB: true}, text: "provider: Anthropic\nmodel family Claude\n"},

		// Class A in files, never allowed.
		{name: "co-authored-by AI", kind: KindFile, opts: Options{AllowClassB: true}, text: "Co-Authored-By: Claude <noreply@anthropic.com>\n", want: []want{{ClassA, 1}}},
		{name: "co-authored-by vendor mail only", kind: KindFile, text: "Co-authored-by: Helper <helper@openai.com>\n", want: []want{{ClassA, 1}}},
		{name: "co-authored-by a person", kind: KindFile, text: "Co-Authored-By: Ada Lovelace <ada@example.com>\n"},
		{name: "session trailer", kind: KindFile, opts: Options{AllowClassB: true}, text: "Claude-Session: https://example.invalid/s\n", want: []want{{ClassA, 1}}},
		{name: "other vendor session trailer", kind: KindFile, text: "Codex-Session: abc\n", want: []want{{ClassA, 1}}},
		{name: "generated with plus assistant in a file", kind: KindFile, opts: Options{AllowClassB: true}, text: "// Generated with Claude Code\n", want: []want{{ClassA, 1}}},
		{name: "written by an AI in a file", kind: KindFile, text: "// Written by an AI\n", want: []want{{ClassA, 1}}},
		{name: "created with LLM in a file", kind: KindFile, text: "<!-- Created with an LLM -->\n", want: []want{{ClassA, 1}}},
		{name: "sqlc header is not flagged", kind: KindFile, text: "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n"},
		{name: "oapi-codegen header is not flagged", kind: KindFile, text: "// Package apigen provides primitives. Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.4.1 DO NOT EDIT.\n"},
		{name: "generated by a tool is fine", kind: KindFile, text: "generated with sqlc and stored in sqlcgen\n"},
		{name: "AI-generated", kind: KindFile, text: "this section is AI-generated\n", want: []want{{ClassA, 1}}},
		{name: "ai written and assisted", kind: KindFile, text: "AI-written\nai assisted\n", want: []want{{ClassA, 1}, {ClassA, 2}}},
		{name: "robot emoji generated", kind: KindFile, text: "\U0001F916 Generated for you\n", want: []want{{ClassA, 1}}},

		// Commit messages.
		{name: "clean commit", kind: KindCommit, text: "fix(engine): honor cancellation\n"},
		{name: "co-authored-by trailer", kind: KindCommit, text: "feat: add retries\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n", want: []want{{ClassA, 3}}},
		{name: "claude session trailer", kind: KindCommit, text: "fix(engine): honor cancellation\n\nClaude-Session: https://example.invalid/s\n", want: []want{{ClassA, 3}}},
		{name: "generated with line always blocks", kind: KindCommit, text: "chore: refresh api types\n\nGenerated with an assistant\n", want: []want{{ClassA, 3}}},
		{name: "generated with a code generator still blocks", kind: KindCommit, text: "chore: refresh api types\n\nGenerated with sqlc\n", want: []want{{ClassA, 3}}},
		{name: "generated with after emoji and markup", kind: KindPR, text: "\U0001F916 Generated with [Some Tool](https://example.invalid)\n", want: []want{{ClassA, 1}}},
		{name: "regenerate wording is fine", kind: KindCommit, text: "chore(api): regenerate with sqlc\n"},
		{name: "claude code in docs scope blocks", kind: KindCommit, text: "docs: generated with Claude Code\n", want: []want{{ClassA, 1}}},
		{name: "OpenAI in docs scope blocks", kind: KindCommit, text: "docs: explain OpenAI usage in the build\n", want: []want{{ClassB, 1}}},
		{name: "ai scope allows vendor names", kind: KindCommit, text: "feat(ai): add Anthropic provider\n"},
		{name: "llm scope allows vendor names", kind: KindCommit, text: "feat(llm): add Anthropic provider\n"},
		{name: "mcp scope allows vendor names", kind: KindCommit, text: "feat(mcp): expose tools to Claude Code clients\n"},
		{name: "scope list with a product scope", kind: KindCommit, text: "feat(api,llm): add Anthropic provider\n"},
		{name: "non product scope blocks", kind: KindCommit, text: "feat(engine): add Anthropic provider\n", want: []want{{ClassB, 1}}},
		{name: "product scope never allows trailers", kind: KindCommit, text: "feat(llm): add Anthropic provider\n\nSigned-off-by: Anthropic fan\n", want: []want{{ClassB, 3}}},
		{name: "product scope body prose is fine", kind: KindCommit, text: "feat(llm): add provider\n\nThe adapter calls the Anthropic Messages API.\n"},
		{name: "co-authored-by is blocked even under a product scope", kind: KindCommit, text: "feat(llm): add provider\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n", want: []want{{ClassA, 3}}},
		{name: "comment lines are ignored", kind: KindCommit, text: "fix: handle nil\n\n# Please enter the commit message. Claude Code is not here.\n"},
		{name: "scissors ends the message", kind: KindCommit, text: "fix: handle nil\n\n# ------------------------ >8 ------------------------\nClaude diff\n"},
		{name: "mneme scope sentence", kind: KindCommit, text: "docs(docs): note that mneme validates the skill\n"},

		// Pull request text keeps the scope chosen by the title.
		{name: "pr body with product title scope", kind: KindPR, opts: Options{AllowClassB: true}, text: "Adds the Anthropic provider.\n"},
		{name: "pr body without product scope", kind: KindPR, text: "Adds the Anthropic provider.\n", want: []want{{ClassB, 1}}},
		{name: "pr body hash heading is kept", kind: KindPR, text: "# Claude notes\n", want: []want{{ClassB, 1}}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := classes(Scan(tt.kind, tt.text, tt.opts))
			if len(got) != len(tt.want) {
				t.Fatalf("findings = %v (%v), want %v", Scan(tt.kind, tt.text, tt.opts), got, tt.want)
			}
			for i := range got {
				if got[i] != tt.want[i] {
					t.Fatalf("finding %d = %+v, want %+v", i, got[i], tt.want[i])
				}
			}
		})
	}
}

func TestProductScope(t *testing.T) {
	tests := map[string]bool{
		"feat(ai): x":        true,
		"fix(LLM): x":        true,
		"feat(mcp)!: x":      true,
		"feat(api, ai): x":   true,
		"feat(engine): x":    false,
		"feat: x":            false,
		"not conventional":   false,
		"docs(docs): the ai": false,
	}
	for subject, want := range tests {
		if got := ProductScope(subject); got != want {
			t.Errorf("ProductScope(%q) = %v, want %v", subject, got, want)
		}
	}
}

