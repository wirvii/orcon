package main

import "regexp"

// The term lists below are the contract of the provenance check (SPEC-008
// 4.11). They change only through a reviewed pull request.
//
// Class B names the assistants used to build Orcon and their vendors. Class A
// is any mark of AI authorship. mneme is the project's own tool and is never
// matched: nothing in this file mentions it, on purpose.

// classBPattern is the alternation shared by every rule that needs "an
// assistant or its vendor". \b keeps "OpenAPI" from matching "OpenAI".
const classBPattern = `claude(?:[ -]code)?|anthropic|codex|openai|chatgpt|(?:github[ -])?copilot`

var (
	// classB matches a class B term.
	classB = regexp.MustCompile(`(?i)\b(?:` + classBPattern + `)\b`)

	// coAuthoredBy matches a Co-Authored-By trailer and captures its value.
	// Comment markers before it are allowed so a trailer pasted into a code
	// comment is still caught.
	coAuthoredBy = regexp.MustCompile(`(?i)^[\s/#*<!>-]*co-authored-by\s*:\s*(.*)$`)

	// vendorMail matches the mail domains of assistant vendors.
	vendorMail = regexp.MustCompile(`(?i)@(?:[a-z0-9-]+\.)*(?:anthropic|openai)\.com\b`)

	// sessionTrailer matches "<class B term>-Session:" trailers.
	sessionTrailer = regexp.MustCompile(`(?i)^[\s/#*<!>-]*(?:` + classBPattern + `)[ -]session\s*:`)

	// generatedLead matches a line that starts, after optional emoji or markup,
	// with "Generated with".
	generatedLead = regexp.MustCompile(`(?i)^[^\p{L}\p{N}]*generated with\b`)

	// generatedByAI matches "Generated with/by", "Written with/by" or "Created
	// with/by" followed on the same line by a class B term or an AI word. This
	// keeps "Code generated by sqlc. DO NOT EDIT." clean.
	generatedByAI = regexp.MustCompile(`(?i)\b(?:generated|written|created) (?:with|by)\b[^\n]*?\b(?:` + classBPattern + `|ai|an ai|a language model|llm|assistant)\b`)

	// aiMarks matches the fixed AI-authorship phrases.
	aiMarks = regexp.MustCompile(`(?i)\bai[- ](?:generated|written|assisted)\b`)

	// robotGenerated matches the robot emoji next to "Generated".
	robotGenerated = regexp.MustCompile(`(?i)(?:\x{1F916}[^\n]*generated|generated[^\n]*\x{1F916})`)

	// conventionalSubject captures the optional scope list of a Conventional
	// Commits subject.
	conventionalSubject = regexp.MustCompile(`^\s*[a-zA-Z]+(?:\(([^)]*)\))?!?:`)

	// trailerLine matches a "Token: value" trailer line.
	trailerLine = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9-]*:\s`)
)

// productScopes are the Conventional Commits scopes that may name assistant
// vendors, because they describe Orcon's own AI features.
var productScopes = map[string]bool{"ai": true, "llm": true, "mcp": true}

// fixHint is appended to every finding.
const fixHint = "remove AI attribution"
