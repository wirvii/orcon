package main

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Func is what the scan found in one C function.
type Func struct {
	Name string
	// Loops counts the loops whose bound depends on the input, Moves the
	// memory moves, copies, comparisons and fills of variable length.
	Loops, Moves int
	// Polls and Charges count the uses of js_poll_work and js_charge_work.
	Polls, Charges int
}

// Checked reports whether the function reaches the interrupt handler or
// charges the counter.
func (f Func) Checked() bool { return f.Polls+f.Charges > 0 }

// pollCalls reach the interrupt handler; chargeCalls only subtract from the
// counter. The first four are the Orcon helpers, the last is the hook of the
// regular expression compiler.
var (
	pollCalls   = []string{"js_poll_work(", "js_poll_interrupts(", "orcon_poll(", "unicode_poll(", "lre_check_timeout("}
	chargeCalls = []string{"js_charge_work(", "js_charge_work_rt("}
)

var (
	loopHead = regexp.MustCompile(`^\s*(for|while)\s*\((.*)$`)
	// A bound that depends on the input names a length, a count or a size.
	inputBound = regexp.MustCompile(`(len|length|count|size|\bn\b|\bnb\b|\bna\b|\bend\b|cap)`)
	memCall    = regexp.MustCompile(`\bmem(move|cpy|cmp|set)\s*\(`)
	constSize  = regexp.MustCompile(`,\s*sizeof\s*\([^()]*\)\s*\)`)
	nameBefore = regexp.MustCompile(`([A-Za-z_][A-Za-z0-9_]*)\s*\(`)
)

// Scan splits the source into top-level functions (a "{" alone at column 0
// opens one and a line that starts with "}" at column 0 closes it, the style of quickjs.c) and
// counts, in each, the input-dependent loops, the variable moves and the polls.
func Scan(src string) []Func {
	lines := strings.Split(src, "\n")
	var out []Func
	for i := 0; i < len(lines); i++ {
		if strings.TrimRight(lines[i], " \t") != "{" {
			continue
		}
		name := signatureName(lines, i)
		f := Func{Name: name}
		j := i + 1
		for ; j < len(lines) && !strings.HasPrefix(lines[j], "}"); j++ {
			ln := lines[j]
			if m := loopHead.FindStringSubmatch(ln); m != nil && inputBound.MatchString(m[2]) {
				f.Loops++
			}
			if memCall.MatchString(ln) && !constSize.MatchString(ln) {
				f.Moves++
			}
			for _, poll := range pollCalls {
				f.Polls += strings.Count(ln, poll)
			}
			for _, charge := range chargeCalls {
				f.Charges += strings.Count(ln, charge)
			}
		}
		if name != "" {
			out = append(out, f)
		}
		i = j
	}
	return out
}

// signatureName finds the name of the function whose body opens at line i.
func signatureName(lines []string, i int) string {
	var sig []string
	for k := i - 1; k >= 0 && k >= i-6; k-- {
		t := strings.TrimSpace(lines[k])
		if t == "" || strings.HasSuffix(t, ";") || strings.HasSuffix(t, "}") || strings.HasSuffix(t, "*/") || strings.HasPrefix(t, "#") {
			break
		}
		sig = append([]string{t}, sig...)
	}
	if m := nameBefore.FindStringSubmatch(strings.Join(sig, " ")); m != nil {
		return m[1]
	}
	return ""
}

// Render writes the report: one line per function that has an
// input-dependent loop or a variable move, sorted by name, then a summary.
func Render(funcs []Func) string {
	var rows []Func
	for _, f := range funcs {
		if f.Loops+f.Moves > 0 {
			rows = append(rows, f)
		}
	}
	sort.SliceStable(rows, func(a, b int) bool { return rows[a].Name < rows[b].Name })
	var b strings.Builder
	b.WriteString("# C functions of quickjs.c (with the Orcon patch) that have a loop bounded by the input\n")
	b.WriteString("# or a memory move of variable length, generated by build.sh with tools/qjsloops.\n")
	b.WriteString("# columns: function loops moves polls charges state (state is checked when the function\n")
	b.WriteString("# polls the interrupt handler or charges the counter, unchecked otherwise).\n")
	unchecked := 0
	for _, f := range rows {
		state := "checked"
		if !f.Checked() {
			state = "unchecked"
			unchecked++
		}
		fmt.Fprintf(&b, "%s %d %d %d %d %s\n", f.Name, f.Loops, f.Moves, f.Polls, f.Charges, state)
	}
	fmt.Fprintf(&b, "# %d functions, %d unchecked\n", len(rows), unchecked)
	return b.String()
}
