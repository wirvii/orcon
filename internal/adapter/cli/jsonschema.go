package cli

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strconv"
	"strings"

	"github.com/wirvii/orcon/internal/platform/config"
)

const (
	durationPattern = `^([0-9]+(\.[0-9]+)?(ns|us|µs|ms|s|m|h))+$`
	bytesPattern    = `^[0-9]+(B|KiB|MiB|GiB|TiB)?$`
	addressPattern  = `^.*:[0-9]+$`
)

// JSONSchema returns the JSON Schema (draft 2020-12) of the YAML configuration
// file, generated from the schema of the keys. The output is deterministic.
func JSONSchema(s *config.Schema) ([]byte, error) {
	props := map[string]any{}
	root := map[string]any{
		"$schema":              "https://json-schema.org/draft/2020-12/schema",
		"$id":                  "urn:orcon:schema:config:1",
		"$comment":             "SPDX-FileCopyrightText: The Orcon Authors. SPDX-License-Identifier: Apache-2.0. Generated by orcon config schema; do not edit.",
		"title":                "Orcon server configuration",
		"description":          "The YAML file passed with --config or ORCON_CONFIG. Keys are camelCase; unknown keys are errors. Flags and environment variables override the file.",
		"type":                 "object",
		"additionalProperties": false,
		"properties":           props,
	}
	for _, k := range s.Keys() {
		insert(props, strings.Split(k.Path, "."), k)
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(root); err != nil {
		return nil, fmt.Errorf("encode JSON Schema: %w", err)
	}
	return buf.Bytes(), nil
}

// insert places the property of k under props, creating a section object for each path segment but the last.
func insert(props map[string]any, segs []string, k *config.Key) {
	if len(segs) == 1 {
		props[segs[0]] = keySchema(k)
		if k.Secret {
			props[segs[0]+"File"] = map[string]any{
				"type":                    "string",
				"description":             "Path of a file that holds the value of " + k.Path + ". Give this or " + segs[0] + ", not both.",
				"x-orcon-env":             k.EnvFileName(),
				"x-orcon-flag":            "--" + k.FlagFileName(),
				"x-orcon-reload":          k.Reload.String(),
				"x-orcon-secret-file-for": k.Path,
			}
		}
		return
	}
	insert(sectionProps(props, segs[0]), segs[1:], k)
}

// sectionProps returns the properties of the section object called name, creating the section on first use.
func sectionProps(props map[string]any, name string) map[string]any {
	if section, ok := props[name].(map[string]any); ok {
		if inner, ok := section["properties"].(map[string]any); ok {
			return inner
		}
	}
	inner := map[string]any{}
	props[name] = map[string]any{"type": "object", "additionalProperties": false, "properties": inner}
	return inner
}

func keySchema(k *config.Key) map[string]any {
	out := scalarSchema(k)
	if k.Kind == config.KindList {
		out = map[string]any{"type": "array", "items": scalarSchema(k)}
	}
	if k.Kind == config.KindMap {
		out = map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "string"}}
	}
	desc := k.Description.EN
	if k.Secret {
		desc += " This is a secret: prefer the file variant."
		out["writeOnly"] = true
	}
	out["description"] = desc
	if k.DefaultFunc == nil && k.Default != "" {
		out["default"] = typedDefault(k)
	}
	out["x-orcon-env"] = k.EnvName()
	if !k.Secret {
		out["x-orcon-flag"] = "--" + k.FlagName()
	}
	out["x-orcon-reload"] = k.Reload.String()
	roles := make([]string, 0, len(k.Roles))
	for _, r := range k.Roles {
		roles = append(roles, string(r))
	}
	if len(roles) > 0 {
		out["x-orcon-roles"] = roles
	}
	return out
}

func scalarSchema(k *config.Key) map[string]any {
	switch k.Kind {
	case config.KindInt:
		out := map[string]any{"type": "integer"}
		rangeOf(out, k)
		return out
	case config.KindFloat:
		out := map[string]any{"type": "number"}
		rangeOf(out, k)
		return out
	case config.KindBool:
		return map[string]any{"type": "boolean"}
	case config.KindDuration:
		return map[string]any{"type": "string", "pattern": durationPattern}
	case config.KindEnum:
		return map[string]any{"type": "string", "enum": k.Enum}
	case config.KindURL:
		return map[string]any{"type": "string", "format": "uri"}
	case config.KindAddress:
		return map[string]any{"type": "string", "pattern": addressPattern}
	case config.KindBytes:
		return map[string]any{"type": []string{"string", "integer"}, "pattern": bytesPattern}
	case config.KindString, config.KindPath, config.KindList, config.KindMap:
		return map[string]any{"type": "string"}
	}
	return map[string]any{"type": "string"}
}

func rangeOf(out map[string]any, k *config.Key) {
	if k.HasRange {
		out["minimum"] = k.Min
		out["maximum"] = k.Max
	}
}

func typedDefault(k *config.Key) any {
	switch k.Kind {
	case config.KindInt:
		if n, err := strconv.Atoi(k.Default); err == nil {
			return n
		}
	case config.KindFloat:
		if f, err := strconv.ParseFloat(k.Default, 64); err == nil {
			return f
		}
	case config.KindBool:
		return k.Default == "true"
	case config.KindList:
		return strings.Split(k.Default, ",")
	case config.KindString, config.KindDuration, config.KindEnum, config.KindPath, config.KindURL, config.KindAddress, config.KindBytes, config.KindMap:
	}
	return k.Default
}
