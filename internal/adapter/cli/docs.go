// GeneratedFile is a reference page or schema that orcon docs generate writes.
type GeneratedFile struct {
	// Path is relative to the output directory, with forward slashes.
	Path string
	// Content is the bytes of the file.
	Content []byte
}

// GenerateDocs renders the references that come from the code: the configuration
// reference in English and Spanish and the JSON Schema of the configuration file
// (decision P3). The CLI and metrics references are added by the cuts that own them.
func GenerateDocs(s *config.Schema) ([]GeneratedFile, error) {
	schema, err := JSONSchema(s)
	if err != nil {
		return nil, err
	}
	return []GeneratedFile{
		{Path: "configuration.md", Content: []byte(renderReference(s, english))},
		{Path: "es/configuration.md", Content: []byte(renderReference(s, spanish))},
		{Path: "configuration.schema.json", Content: schema},
	}, nil
}

func runDocs(args []string, env Env) int {
	if len(args) == 0 || args[0] != "generate" {
		_, _ = io.WriteString(env.Stderr, "usage: orcon docs generate --out <directory>\n")
		return ExitUsage
	}
	fs := flag.NewFlagSet("orcon docs generate", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	out := fs.String("out", "docs/reference", "directory the references are written to")
	if err := fs.Parse(args[1:]); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			_, _ = io.WriteString(env.Stdout, "usage: orcon docs generate [--out <directory>]\n")
			return ExitOK
		}
		return usagef(env, "%v", err)
	}
	files, err := GenerateDocs(env.schema())
	if err == nil {
		err = writeFiles(*out, files)
	}
	if err != nil {
		_, _ = fmt.Fprintf(env.Stderr, "orcon: %v\n", err)
		return ExitError
	}
	for _, f := range files {
		_, _ = fmt.Fprintln(env.Stdout, filepath.Join(*out, filepath.FromSlash(f.Path)))
	}
	return ExitOK
}

func writeFiles(dir string, files []GeneratedFile) error {
	for _, f := range files {
		path := filepath.Join(dir, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			return fmt.Errorf("create directory: %w", err)
		}
		if err := os.WriteFile(path, f.Content, 0o600); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
	}
	return nil
}

