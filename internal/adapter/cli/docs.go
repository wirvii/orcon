func (l *lang) describe(t config.Text) string {
	if l.code == "es" {
		return t.ES
	}
	return t.EN
}

func renderReference(s *config.Schema, l *lang) string {
	var b strings.Builder
	b.WriteString("<!-- SPDX-FileCopyrightText: The Orcon Authors -->\n<!-- SPDX-License-Identifier: Apache-2.0 -->\n")
	fmt.Fprintf(&b, "<!-- %s -->\n", strings.NewReplacer("`", "").Replace(l.generated))
	fmt.Fprintf(&b, "# %s\n\n", l.title)
	for _, p := range l.intro {
		b.WriteString(p)
		b.WriteString("\n\n")
	}
	fmt.Fprintf(&b, "## %s\n\n", l.settings)
	group := "\x00" // never a real group, so the first heading is always written
	for _, k := range s.Keys() {
		g := groupOf(k.Path)
		if g != group {
			group = g
			title := "`" + g + "`"
			if g == "" {
				title = l.general
			}
			fmt.Fprintf(&b, "### %s\n\n", title)
		}
		renderKey(&b, k, l)
	}
	return b.String()
}

// groupOf is the first segment of a path, or "" for a key that is not in a section.
func groupOf(path string) string {
	first, _, nested := strings.Cut(path, ".")
	if !nested {
		return ""
	}
	return first
}

func renderKey(b *strings.Builder, k *config.Key, l *lang) {
	fmt.Fprintf(b, "#### `%s`\n\n%s\n\n", k.Path, l.describe(k.Description))
	b.WriteString("| | |\n|---|---|\n")
	fmt.Fprintf(b, "| %s | %s |\n", l.typeLabel, typeText(k, l))
	fmt.Fprintf(b, "| %s | %s |\n", l.defaultLbl, defaultText(k, l))
	fmt.Fprintf(b, "| %s | `%s` |\n", l.envLabel, k.EnvName())
	if k.Secret {
		fmt.Fprintf(b, "| %s | %s |\n", l.flagLabel, l.noFlag)
	} else {
		fmt.Fprintf(b, "| %s | `--%s` |\n", l.flagLabel, k.FlagName())
	}
	fmt.Fprintf(b, "| %s | %s |\n", l.reloadLabel, l.reloadNames[k.Reload])
	fmt.Fprintf(b, "| %s | %s |\n", l.rolesLabel, rolesText(k, l))
	if k.Secret {
		fmt.Fprintf(b, "| %s | %s |\n", l.hiddenLabel, fmt.Sprintf(l.fileNote, k.FileKey(), k.EnvFileName(), k.FlagFileName()))
	}
	b.WriteString("\n")
}

func typeText(k *config.Key, l *lang) string {
	t := kindName(k.Kind, l)
	switch {
	case k.Kind == config.KindEnum:
		quoted := make([]string, 0, len(k.Enum))
		for _, e := range k.Enum {
			quoted = append(quoted, "`"+e+"`")
		}
		return l.valuesLabel + " " + strings.Join(quoted, ", ")
	case k.HasRange:
		return fmt.Sprintf(l.rangeFmt, t, fmtNumber(k.Min), fmtNumber(k.Max))
	default:
		return t
	}
}

func fmtNumber(f float64) string {
	return strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.4f", f), "0"), ".")
}

func defaultText(k *config.Key, l *lang) string {
	switch {
	case k.DefaultFunc != nil && (k.DefaultDoc.EN != "" || k.DefaultDoc.ES != ""):
		return l.describe(k.DefaultDoc)
	case k.Default != "":
		return "`" + k.Default + "`"
	default:
		return l.none
	}
}

func rolesText(k *config.Key, l *lang) string {
	if len(k.Roles) == 0 {
		return l.allRoles
	}
	names := make([]string, 0, len(k.Roles))
	for _, r := range k.Roles {
		names = append(names, "`"+string(r)+"`")
	}
	return strings.Join(names, ", ")
}

// kindName names a kind in the language of the page.
func kindName(k config.Kind, l *lang) string {
	if l.code != "es" {
		return k.String()
	}
	switch k {
	case config.KindString:
		return "texto"
	case config.KindInt:
		return "entero"
	case config.KindFloat:
		return "número"
	case config.KindBool:
		return "booleano"
	case config.KindDuration:
		return "duración"
	case config.KindPath:
		return "ruta"
	case config.KindAddress:
		return "host:puerto"
	case config.KindList:
		return "lista"
	case config.KindMap:
		return "mapa"
	case config.KindEnum, config.KindURL, config.KindBytes:
		return k.String()
	}
	return k.String()
}
