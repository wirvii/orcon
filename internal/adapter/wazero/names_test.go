var update = flag.Bool("update", false, "rewrite internal/expr/names_gen.go from the sandbox")

const namesFile = "../../expr/names_gen.go"

// enumerate lists, by evaluating JavaScript in the sandbox, the method names
// the analysis accepts and the property names of the prototypes the fast path
// must not guess at. The lists are generated from the runtime so they cannot
// drift from the prelude.
const enumerate = `={{ (() => {
  const methods = new Set();
  const addFns = (obj) => {
    for (let o = obj; o !== null && o !== undefined; o = Object.getPrototypeOf(o)) {
      for (const k of Reflect.ownKeys(o)) {
        if (typeof k !== 'string') continue;
        const d = Object.getOwnPropertyDescriptor(o, k);
        if (d && typeof d.value === 'function') methods.add(k);
      }
    }
  };
  const subjects = [Object, Array, Number, String, Boolean, Math, JSON, Date, Reflect, Symbol, BigInt, RegExp,
    Map, Set, WeakMap, WeakSet, ArrayBuffer, Uint8Array, DataView, Error, Function, Intl, crypto,
    DateTime, Duration, Interval,
    Intl.DateTimeFormat, Intl.NumberFormat, Intl.RelativeTimeFormat, Intl.ListFormat, globalThis];
  for (const s of subjects) { addFns(s); if (typeof s === 'function' && s.prototype) addFns(s.prototype); }
  addFns(DateTime.now()); addFns(Duration.fromMillis(1)); addFns(Interval.after(DateTime.now(), 1));
  addFns(new Map().entries()); addFns([][Symbol.iterator]()); addFns(''.matchAll(/x/g)); addFns(/x/.exec('x') || []);
  methods.delete('__orcon_run');
  const names = (o) => Reflect.ownKeys(o).filter((k) => typeof k === 'string');
  return { methods: [...methods], object: names(Object.prototype), array: names(Array.prototype), string: names(String.prototype) };
})() }}`

// TestKnownIdentifiers keeps the identifier lists of the analysis equal to
// what the sandbox defines: every listed name resolves, and every global the
// sandbox defines is listed.
func TestKnownIdentifiers(t *testing.T) {
	ev := evaluator(t, expr.Options{DisableFastPath: true})
	s := ev.Open()
	t.Cleanup(func() { _ = s.Close(t.Context()) })
	env := newEnv(t, `{}`)
	eval := func(src string) []string {
		p, err := ev.Compile(src)
		if err != nil {
			t.Fatal(err)
		}
		res, err := s.Eval(t.Context(), p, env)
		if err != nil {
			t.Fatalf("Eval(%s): %v", src, err)
		}
		var out []string
		for _, it := range res.Value.Items() {
			name, _ := it.Str()
			out = append(out, name)
		}
		return out
	}
	listed := append(expr.ContextNames(), expr.GlobalNames()...)
	// typeof of an undeclared name does not throw, so a missing definition is
	// reported by name instead of failing the whole evaluation.
	var tests []string
	for _, name := range listed {
		if name == "undefined" {
			continue // typeof undefined is, by definition, "undefined"
		}
		tests = append(tests, fmt.Sprintf("(typeof %s === 'undefined' ? %q : '')", name, name))
	}
	for _, missing := range eval("={{ [" + strings.Join(tests, ",") + "].filter(Boolean) }}") {
		t.Errorf("%s is listed as defined but the sandbox does not define it", missing)
	}
	defined := eval(`={{ Reflect.ownKeys(globalThis).filter((k) => typeof k === 'string') }}`)
	for _, name := range defined {
		// __orcon_run is the entry point and luxon is emptied by the hardening script.
		if name == "__orcon_run" || name == "luxon" || slices.Contains(listed, name) {
			continue
		}
		t.Errorf("the sandbox defines the global %s, which expr.GlobalNames does not list", name)
	}
}

func TestGeneratedNames(t *testing.T) {
	ev := evaluator(t, expr.Options{DisableFastPath: true})
	s := ev.Open()
	t.Cleanup(func() { _ = s.Close(t.Context()) })
	p, err := ev.Compile(enumerate)
	if err != nil {
		t.Fatal(err)
	}
	res, err := s.Eval(t.Context(), p, newEnv(t, `{}`))
	if err != nil {
		t.Fatalf("enumerate: %v", err)
	}
	get := func(key string) []string {
		member, ok := res.Value.Get(key)
		if !ok {
			t.Fatalf("no %s in the answer", key)
		}
		var out []string
		for _, it := range member.Items() {
			name, _ := it.Str()
			out = append(out, name)
		}
		slices.Sort(out)
		return slices.Compact(out)
	}
	var b bytes.Buffer
	b.WriteString("// SPDX-FileCopyrightText: The Orcon Authors\n// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("// Code generated by TestGeneratedNames in internal/adapter/wazero; DO NOT EDIT.\n\npackage expr\n\n")
	b.WriteString("// methodNames are the method names the analysis accepts: every function-valued property of the\n")
	b.WriteString("// JavaScript built-ins, Luxon and the extension methods, by name.\n")
	b.WriteString("// objectProto, arrayProto and stringProto are the property names of those prototypes, which the\n")
	b.WriteString("// fast path leaves to the interpreter when the data lacks the property.\n")
	for _, set := range []struct{ name, key string }{{"methodNames", "methods"}, {"objectProto", "object"}, {"arrayProto", "array"}, {"stringProto", "string"}} {
		fmt.Fprintf(&b, "var %s = map[string]struct{}{\n", set.name)
		for _, n := range get(set.key) {
			fmt.Fprintf(&b, "\t%q: {},\n", n)
		}
		b.WriteString("}\n\n")
	}
	got, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile(namesFile, got, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(namesFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(want, got) {
		t.Fatalf("internal/expr/names_gen.go is out of date with the prelude; run: go test ./internal/adapter/wazero -run TestGeneratedNames -update")
	}
}
