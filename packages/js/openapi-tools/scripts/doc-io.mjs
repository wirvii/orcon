import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

import { parse, stringify } from 'yaml';

export const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

/** Reads a bundled OpenAPI document (YAML or JSON). */
export function readDocument(file) {
  return parse(readFileSync(resolve(file), 'utf8'));
}

/** Writes text, creating parent directories. */
export function writeText(file, text) {
  mkdirSync(dirname(resolve(file)), { recursive: true });
  writeFileSync(resolve(file), text);
}

export function writeYaml(file, doc) {
  writeText(file, stringify(doc, { lineWidth: 0 }));
}

export function writeJson(file, doc) {
  writeText(file, `${JSON.stringify(doc, null, 2)}\n`);
}

/** Every operation of paths and webhooks: [{ kind, key, method, op, item }]. */
export function operationsOf(doc) {
  const out = [];
  for (const [kind, map] of [['path', doc.paths], ['webhook', doc.webhooks]]) {
    for (const [key, item] of Object.entries(map ?? {})) {
      for (const method of METHODS) {
        if (item?.[method]) out.push({ kind, key, method, op: item[method], item });
      }
    }
  }
  return out;
}

const AUTO_HEADER = [
  '<!-- SPDX-FileCopyrightText: The Orcon Authors -->',
  '<!-- SPDX-License-Identifier: Apache-2.0 -->',
].join('\n');

/** The header every generated Markdown file starts with. */
export function generatedHeader(generator) {
  return `${AUTO_HEADER}\n<!-- Generated by ${generator}. Do not edit by hand. -->\n`;
}

/** Escapes a table cell. */
export const cell = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();

/** Formats the permission extension for people. */
export function formatPermission(value) {
  if (typeof value === 'string') return `\`${value}\``;
  if (value?.allOf) return `all of ${value.allOf.map((p) => `\`${p}\``).join(', ')}`;
  if (value?.anyOf) return `any of ${value.anyOf.map((p) => `\`${p}\``).join(', ')}`;
  return 'not declared';
}

/** The problem code catalog of a bundled document: Map(code -> { status, title, when, retryable }). */
export function problemCatalog(doc) {
  const catalog = doc.components?.schemas?.ProblemCode?.['x-orcon-problem-catalog'] ?? {};
  return new Map(Object.entries(catalog));
}

/** Exits with an error unless `condition`. */
export function must(condition, message) {
  if (!condition) {
    process.stderr.write(`${message}\n`);
    process.exit(1);
  }
}
