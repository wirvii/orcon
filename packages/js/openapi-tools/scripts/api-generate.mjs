/**
 * The committed artifacts derived from the contract (spec sections 4.1 and 4.7):
 *
 *   packages/openapi/v1/openapi.bundle.yaml   the bundle the Go generator reads (SPDX header added)
 *   packages/openapi/v1/openapi.bundle.json   the same bundle for Go tests
 *   docs/reference/problem-codes.md           the problem code catalog
 *   docs/reference/api/README.md              the operation index
 *
 *   node scripts/api-generate.mjs [--check]
 *
 * Without --check the files are written; with --check nothing is written and the exit status
 * is 1 when a file differs (the drift check of `make api-lint`). With no contract it says so
 * and exits 0.
 */

import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';

import { bundle } from './bundle.mjs';
import { readDocument, writeText } from './doc-io.mjs';
import { defaultContract, isMain, parseArgs, repoRoot } from './lib.mjs';
import { renderOperationIndex } from './operation-index.mjs';
import { renderProblemCodes } from './problem-codes.mjs';

const SPDX = '# SPDX-FileCopyrightText: The Orcon Authors\n# SPDX-License-Identifier: Apache-2.0\n# GENERATED by packages/js/openapi-tools (make api-lint); do not edit.\n';

/** The artifacts as Map(path relative to the repository root -> text). */
export function artifacts() {
  const dir = mkdtempSync(join(tmpdir(), 'orcon-api-generate-'));
  try {
    const yaml = join(dir, 'bundle.yaml');
    const json = join(dir, 'bundle.json');
    bundle(defaultContract(), yaml);
    bundle(defaultContract(), json);
    const contractDir = relative(repoRoot(), join(defaultContract(), '..'));
    const doc = readDocument(yaml);
    return new Map([
      [join(contractDir, 'openapi.bundle.yaml'), SPDX + readFileSync(yaml, 'utf8')],
      [join(contractDir, 'openapi.bundle.json'), readFileSync(json, 'utf8')],
      [join('docs', 'reference', 'problem-codes.md'), renderProblemCodes(doc)],
      [join('docs', 'reference', 'api', 'README.md'), renderOperationIndex(doc)],
    ]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (isMain(import.meta.url)) {
  const { flags } = parseArgs(process.argv.slice(2), ['check']);
  if (!existsSync(defaultContract())) {
    process.stdout.write(`api-generate: no contract at ${defaultContract()}; nothing to generate\n`);
    process.exit(0);
  }
  const stale = [];
  for (const [file, text] of artifacts()) {
    const path = join(repoRoot(), file);
    if (flags.check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== text) stale.push(file);
    } else {
      writeText(path, text);
    }
  }
  if (stale.length > 0) {
    process.stderr.write(`api-generate: out of date: ${stale.join(', ')}; run make api-generate and commit the result\n`);
    process.exit(1);
  }
}
