/**
 * Builds the API reference site (P1, spec section 4.7): the decorated contract rendered by
 * Scalar with "try it", with no CDN and no external resource.
 *
 *   node scripts/build-reference.mjs --input <openapi.yaml> --output <dir> [--base-path /api/reference/]
 *
 * Output: index.html, reference-config.js, openapi.json, scalar.standalone.js (copied from
 * node_modules), LICENSE-scalar.txt. The build fails when
 *   - index.html, the config or openapi.json load a resource from another origin,
 *   - the vendored script mentions a host that assets/scalar-hosts.yaml does not list
 *     (a Scalar upgrade has to be reviewed), or
 *   - the compressed site is larger than 3 MiB (the budget of ADR 0080 section 10).
 */

import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

import { parse } from 'yaml';

import { bundle } from './bundle.mjs';
import { decorate } from './decorate.mjs';
import { must, readDocument, writeJson } from './doc-io.mjs';
import { isMain, packageDir, parseArgs } from './lib.mjs';

export const BUDGET_BYTES = 3 * 1024 * 1024;

/** Absolute path of the standalone script of the installed Scalar package. */
export function scalarScript() {
  // The package restricts "exports", so the file is addressed through node_modules.
  const file = join(packageDir, 'node_modules', '@scalar', 'api-reference', 'dist', 'browser', 'standalone.js');
  must(existsSync(file), `Scalar script not found at ${file}; run pnpm install`);
  return file;
}

/** The license notice shipped next to the script: the body of assets/scalar-license.md. */
export function licenseText() {
  const text = readFileSync(join(packageDir, 'assets', 'scalar-license.md'), 'utf8');
  return text.replace(/^(<!--[^\n]*-->\n)+\n?/, '');
}

const escapeHtml = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

export function renderIndexHtml(title, basePath) {
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <base href="${escapeHtml(basePath)}" />
    <title>${escapeHtml(title)}</title>
  </head>
  <body>
    <div id="app"></div>
    <noscript>The Orcon API reference needs JavaScript. The contract is available as openapi.json.</noscript>
    <script src="scalar.standalone.js"></script>
    <script src="reference-config.js"></script>
  </body>
</html>
`;
}

/**
 * The configuration script. It is a file of its own because the content security policy of
 * the binary (default-src 'self') does not allow inline scripts.
 */
export function renderConfigJs(serverUrl) {
  return `// SPDX-FileCopyrightText: The Orcon Authors
// SPDX-License-Identifier: Apache-2.0
//
// Generated by scripts/build-reference.mjs of @orcon/openapi-tools.
// Same-origin only: no proxy, no fonts from a CDN, no telemetry, no cookies in "try it".
Scalar.createApiReference('#app', {
  url: 'openapi.json',
  servers: [{ url: ${JSON.stringify(serverUrl)}, description: 'This server' }],
  authentication: { preferredSecurityScheme: 'bearer' },
  persistAuth: false,
  telemetry: false,
  withDefaultFonts: false,
  hideClientButton: true,
  showDeveloperTools: 'never',
  mcp: { disabled: true },
  agent: { disabled: true },
  customFetch: (input, init) => fetch(input, { ...init, credentials: 'omit' }),
});
`;
}

/** Hosts mentioned as http(s) URLs in a text. */
export function hostsIn(text) {
  const hosts = new Set();
  for (const m of text.matchAll(/https?:\/\/([A-Za-z0-9.-]+)/g)) hosts.add(m[1].toLowerCase());
  return [...hosts].sort();
}

/** Problems with the files that are ours: any resource loaded from another origin. */
export function externalResourceProblems({ html, config, openapi }) {
  const problems = [];
  for (const m of html.matchAll(/\b(?:src|href|action|poster)\s*=\s*"([^"]*)"/g)) {
    if (/^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(m[1]) && !m[1].startsWith('data:')) problems.push(`index.html loads ${m[1]}`);
  }
  if (/@import|url\(\s*["']?https?:/i.test(html)) problems.push('index.html imports a stylesheet from another origin');
  for (const host of hostsIn(config)) problems.push(`reference-config.js mentions ${host}`);
  const text = JSON.stringify(openapi);
  for (const m of text.matchAll(/"\$ref":"(https?:[^"]*)"/g)) problems.push(`openapi.json has an external $ref ${m[1]}`);
  for (const server of openapi.servers ?? []) {
    if (/^https?:|^\/\//.test(server.url ?? '')) problems.push(`openapi.json server ${server.url} is not same-origin`);
  }
  return problems;
}

function gzipSize(file) {
  return gzipSync(readFileSync(file), { level: 9 }).length;
}

/** Builds the site. Returns { files: [{ name, bytes, gzip }], gzipTotal, hosts }. */
export function buildReference({ input, output, basePath = '/api/reference/' }) {
  const out = resolve(output);
  mkdirSync(out, { recursive: true });
  const tmp = mkdtempSync(join(tmpdir(), 'orcon-reference-'));
  try {
    const bundled = join(tmp, 'openapi.bundle.yaml');
    bundle(input, bundled);
    const published = decorate(readDocument(bundled));
    const serverUrl = published.servers?.[0]?.url ?? '/api/v1';
    published.servers = [{ url: serverUrl }];
    writeJson(join(out, 'openapi.json'), published);
    writeFileSync(join(out, 'index.html'), renderIndexHtml(published.info?.title ?? 'API reference', basePath));
    writeFileSync(join(out, 'reference-config.js'), renderConfigJs(serverUrl));
    copyFileSync(scalarScript(), join(out, 'scalar.standalone.js'));
    writeFileSync(join(out, 'LICENSE-scalar.txt'), licenseText());
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }

  const problems = externalResourceProblems({
    html: readFileSync(join(out, 'index.html'), 'utf8'),
    config: readFileSync(join(out, 'reference-config.js'), 'utf8'),
    openapi: JSON.parse(readFileSync(join(out, 'openapi.json'), 'utf8')),
  });
  const allowed = new Set(parse(readFileSync(join(packageDir, 'assets', 'scalar-hosts.yaml'), 'utf8')).hosts);
  const hosts = hostsIn(readFileSync(join(out, 'scalar.standalone.js'), 'utf8'));
  for (const host of hosts) {
    if (!allowed.has(host)) problems.push(`scalar.standalone.js mentions ${host}, which assets/scalar-hosts.yaml does not list; review it, then add it`);
  }
  const files = readdirSync(out)
    .sort()
    .map((name) => ({ name, bytes: statSync(join(out, name)).size, gzip: gzipSize(join(out, name)) }));
  const gzipTotal = files.reduce((sum, f) => sum + f.gzip, 0);
  if (gzipTotal > BUDGET_BYTES) problems.push(`the site is ${gzipTotal} bytes compressed; the budget is ${BUDGET_BYTES} (3 MiB). A larger budget amends ADR 0080`);
  return { files, gzipTotal, hosts, problems };
}

if (isMain(import.meta.url)) {
  const { flags } = parseArgs(process.argv.slice(2));
  must(flags.input && flags.output, 'usage: build-reference.mjs --input <openapi.yaml> --output <dir> [--base-path /api/reference/]');
  must(existsSync(resolve(flags.input)), `contract not found: ${flags.input}`);
  const result = buildReference({ input: flags.input, output: flags.output, basePath: flags['base-path'] });
  for (const f of result.files) process.stdout.write(`  ${f.name.padEnd(24)} ${String(f.bytes).padStart(9)} bytes  ${String(f.gzip).padStart(9)} gzip\n`);
  process.stdout.write(`api-reference: ${flags.output} gzip total ${result.gzipTotal} bytes (budget ${BUDGET_BYTES})\n`);
  if (result.problems.length > 0) {
    for (const p of result.problems) process.stderr.write(`api-reference: ${p}\n`);
    process.exit(1);
  }
}
