/**
 * Regenerates testdata/compat/<case>/{base,head,expect}.yaml.
 *
 *   node test/support/write-compat-cases.mjs
 */

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { packageDir } from '../../scripts/lib.mjs';
import { changelogPair } from './changelog-case.mjs';
import { buildCompatCases } from './compat-cases.mjs';

const root = join(packageDir, 'testdata', 'compat');
rmSync(root, { recursive: true, force: true });
const cases = buildCompatCases();
for (const [name, files] of cases) {
  const dir = join(root, name);
  mkdirSync(dir, { recursive: true });
  const header = '# SPDX-FileCopyrightText: The Orcon Authors\n# SPDX-License-Identifier: Apache-2.0\n# GENERATED by test/support/write-compat-cases.mjs; do not edit.\n';
  writeFileSync(join(dir, 'base.yaml'), header + files.base);
  writeFileSync(join(dir, 'head.yaml'), header + files.head);
  writeFileSync(join(dir, 'expect.yaml'), header + files.expect);
}

const changelogDir = join(packageDir, 'testdata', 'changelog');
mkdirSync(changelogDir, { recursive: true });
const pair = changelogPair();
const header = '# SPDX-FileCopyrightText: The Orcon Authors\n# SPDX-License-Identifier: Apache-2.0\n# GENERATED by test/support/write-compat-cases.mjs; do not edit.\n';
writeFileSync(join(changelogDir, 'base.yaml'), header + pair.base);
writeFileSync(join(changelogDir, 'head.yaml'), header + pair.head);
process.stdout.write(`wrote ${cases.size} compatibility pairs to ${root} and the changelog pair to ${changelogDir}\n`);
