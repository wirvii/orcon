// Turns the token model from load.mjs into the published files. Every
// function returns text so tests can inspect the output without a build.

const HEADER = 'Generated by @orcon/tokens from src/**. Do not edit.';
const SPDX = [
  'SPDX-FileCopyrightText: The Orcon Authors',
  'SPDX-License-Identifier: Apache-2.0',
];

const cssHeader = `/* ${SPDX[0]} */\n/* ${SPDX[1]} */\n/* ${HEADER} */\n`;
const jsHeader = `// ${SPDX[0]}\n// ${SPDX[1]}\n// ${HEADER}\n`;

const declare = (token, indent = '  ') => `${indent}${token.cssName}: ${token.css};`;
const block = (selector, lines, indent = '') =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}${l}`).join('\n')}\n${indent}}`;

const isDuration = (token) => token.path[0] === 'duration';

/** Theme-specific declarations for one theme. */
function themeLines(tokens) {
  return tokens.map((t) => declare(t));
}

export function emitCss(model) {
  const { scales, brand, themes, densities, component } = model;
  const light = themes.light;
  const dark = themes.dark;

  const root = [
    '  color-scheme: light;',
    '',
    '  /* Brand-exact colors: logo, decorative fills, borders and canvas lines. Never text. */',
    ...brand.map((t) => declare(t)),
    '',
    '  /* Scales */',
    ...scales.map((t) => declare(t)),
    '',
    '  /* Light theme */',
    ...themeLines(light),
    '',
    '  /* Comfortable density */',
    ...densities.comfortable.map((t) => declare(t)),
    '',
    '  /* Component tokens follow the active theme and density through references. */',
    ...component.map((t) => {
      const target = [...light, ...densities.comfortable].find((x) => x.key === t.reference);
      return `  ${t.cssName}: var(${target.cssName});`;
    }),
  ];

  const darkLines = ['  color-scheme: dark;', ...themeLines(dark)];
  const durations = scales.filter(isDuration);

  return [
    cssHeader,
    block(':root', root),
    '',
    block('@media (prefers-color-scheme: dark)', [block(':root:not([data-theme="light"])', darkLines, '  ')]),
    '',
    block('[data-theme="dark"]', darkLines),
    '',
    block('[data-theme="light"]', ['  color-scheme: light;', ...themeLines(light)]),
    '',
    block('[data-density="compact"]', densities.compact.map((t) => declare(t))),
    '',
    block('[data-density="comfortable"]', densities.comfortable.map((t) => declare(t))),
    '',
    block('@media (pointer: coarse)', [
      block(':root', ['  --orcon-size-target-min: var(--orcon-size-target-min-coarse);'], '  '),
    ]),
    '',
    block('@media (prefers-reduced-motion: reduce)', [
      block(':root', durations.map((t) => `  ${t.cssName}: 0ms;`), '  '),
    ]),
    '',
  ].join('\n');
}

/** Name of the Tailwind color for a semantic color token key. */
export function tailwindColorName(key) {
  const [group, ...rest] = key.split('.');
  const tail = rest.join('-');
  switch (group) {
    case 'bg':
      return rest[0];
    case 'action': {
      const [family, role] = rest;
      return role === 'bg' ? `action-${family}` : `action-${family}-${role.replace(/^bg-/, '')}`;
    }
    case 'border':
      return rest[0] === 'default' ? 'border' : rest[0];
    case 'focus':
      return 'focus';
    case 'status': {
      const [family, role] = rest;
      return role === 'fg' ? `status-${family}` : `status-${family}-bg`;
    }
    case 'overlay':
      return rest[0];
    case 'canvas':
      return rest[0] === 'bg' ? 'canvas' : `canvas-${tail}`;
    case 'surface':
      return rest[0] === 'default' ? 'surface' : `surface-${rest[0]}`;
    case 'fg':
      return rest[0] === 'default' ? 'fg' : `fg-${rest[0]}`;
    default:
      throw new Error(`No Tailwind color name for ${key}`);
  }
}

// Namespaces that are reset so Tailwind's defaults generate nothing.
const RESETS = [
  '--color-*',
  '--spacing-*',
  '--radius-*',
  '--shadow-*',
  '--inset-shadow-*',
  '--drop-shadow-*',
  '--text-shadow-*',
  '--blur-*',
  '--font-*',
  '--text-*',
  '--tracking-*',
  '--leading-*',
  '--breakpoint-*',
  '--container-*',
  '--ease-*',
  '--animate-*',
  '--perspective-*',
  '--aspect-*',
];

export function emitTailwindTheme(model) {
  const { scales, themes, densities } = model;
  const colorKeys = themes.light.filter((t) => t.type === 'color');
  const v = (token) => `var(${token.cssName})`;
  const lines = [];
  const add = (name, value) => lines.push(`  ${name}: ${value};`);

  lines.push('  /* Reset: Tailwind default palette and scales generate no utilities. */');
  for (const reset of RESETS) add(reset, 'initial');

  lines.push('', '  /* Colors: semantic tokens only. Brand-exact colors are not utilities. */');
  for (const t of colorKeys) add(`--color-${tailwindColorName(t.key)}`, v(t));

  lines.push('', '  /* Spacing scale and density sizes */');
  for (const t of scales.filter((x) => x.path[0] === 'space')) add(`--spacing-${t.path[1]}`, v(t));
  const sizeAlias = {
    'size.row': 'row',
    'size.control': 'control',
    'space.control-x': 'control-x',
    'space.gap': 'density',
    'size.connector-icon': 'connector-icon',
    'size.connector-icon-safe': 'connector-icon-safe',
    'size.node-width': 'node-width',
    'size.control-node-height': 'control-node',
  };
  for (const t of densities.comfortable) add(`--spacing-${sizeAlias[t.key]}`, v(t));
  for (const t of scales.filter((x) => x.path[0] === 'size' && x.path[1] === 'icon')) {
    add(`--spacing-icon-${t.path[2]}`, v(t));
  }
  const target = scales.find((x) => x.key === 'size.target-min');
  add('--spacing-target', v(target));

  lines.push('', '  /* Radius and elevation */');
  for (const t of scales.filter((x) => x.path[0] === 'radius')) add(`--radius-${t.path[1]}`, v(t));
  for (const t of themes.light.filter((x) => x.path[0] === 'elevation')) add(`--shadow-${t.path[1]}`, v(t));

  lines.push('', '  /* Typography */');
  for (const t of scales.filter((x) => x.path[0] === 'font' && x.path[1] === 'family')) {
    add(`--font-${t.path[2]}`, v(t));
  }
  for (const t of scales.filter((x) => x.path[0] === 'font' && x.path[1] === 'size')) {
    add(`--text-${t.path[2]}`, v(t));
    add(`--text-${t.path[2]}--line-height`, `var(--orcon-font-line-height-${t.path[2]})`);
  }
  for (const t of scales.filter((x) => x.path[0] === 'font' && x.path[1] === 'weight')) {
    add(`--font-weight-${t.path[2]}`, v(t));
  }

  lines.push('', '  /* Breakpoints are literal values: media queries cannot read variables. */');
  for (const t of scales.filter((x) => x.path[0] === 'breakpoint')) add(`--breakpoint-${t.path[1]}`, t.css);

  lines.push('', '  /* Easing */');
  for (const t of scales.filter((x) => x.path[0] === 'easing')) add(`--ease-${t.path[1]}`, v(t));

  return `${cssHeader}\n@theme inline {\n${lines.join('\n')}\n}\n`;
}

const flat = (tokens) => Object.fromEntries(tokens.map((t) => [t.key, t.css]));

export function buildData(model) {
  return {
    brand: flat(model.brand),
    scales: flat(model.scales),
    themes: { light: flat(model.themes.light), dark: flat(model.themes.dark) },
    densities: {
      comfortable: flat(model.densities.comfortable),
      compact: flat(model.densities.compact),
    },
  };
}

export function emitJson(model) {
  return `${JSON.stringify(buildData(model), null, 2)}\n`;
}

export function emitJs(model) {
  const data = buildData(model);
  return `${jsHeader}
export const tokens = ${JSON.stringify(data, null, 2)};

/** CSS custom property name for a token key such as "fg.muted". */
export function cssVar(key) {
  return \`--orcon-\${key.replaceAll('.', '-')}\`;
}
`;
}

export function emitDts(model) {
  const data = buildData(model);
  const union = (obj) => Object.keys(obj).map((k) => `'${k}'`).join(' | ');
  return `${jsHeader}
export type BrandTokenName = ${union(data.brand)};
export type ScaleTokenName = ${union(data.scales)};
export type SemanticTokenName = ${union(data.themes.light)};
export type DensityTokenName = ${union(data.densities.comfortable)};
export type ThemeName = 'light' | 'dark';
export type DensityName = 'comfortable' | 'compact';

export interface Tokens {
  brand: Record<BrandTokenName, string>;
  scales: Record<ScaleTokenName, string>;
  themes: Record<ThemeName, Record<SemanticTokenName, string>>;
  densities: Record<DensityName, Record<DensityTokenName, string>>;
}

export declare const tokens: Tokens;
export declare function cssVar(
  key: BrandTokenName | ScaleTokenName | SemanticTokenName | DensityTokenName,
): string;
`;
}
