import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { MINIMUM, evaluatePairs, ratio, type Pair } from './helpers/contrast';
import { colorValues, pairs, themeNames } from './helpers/model';

const here = dirname(fileURLToPath(import.meta.url));
const reportPath = join(here, '..', '..', '..', '..', '.agents', 'skills', 'orcon-ui', 'references', 'contrast-report.md');

const certified = pairs.filter((p) => p.kind === 'text' || p.kind === 'ui');

describe('declared pairs', () => {
  it.each(themeNames)('every pair holds in the %s theme', (theme) => {
    expect(evaluatePairs(pairs, colorValues(theme))).toEqual([]);
  });

  it('certifies 106 text and UI pairs per theme', () => {
    expect(certified).toHaveLength(106);
  });

  it('keeps the policy minimums', () => {
    expect(MINIMUM).toEqual({ text: 4.5, ui: 3 });
    for (const pair of certified) {
      expect(pair.min, `${pair.fg} on ${pair.bg}`).toBeGreaterThanOrEqual(MINIMUM[pair.kind as 'text' | 'ui']);
    }
  });
});

describe('ratios match the values certified in the specification', () => {
  const expected: [string, string, string, 'light' | 'dark', number][] = [
    ['fg.default', 'bg.app', 'text', 'light', 17.06],
    ['fg.subtle', 'surface.default', 'text', 'light', 4.76],
    ['action.primary.fg', 'action.primary.bg', 'text', 'light', 5.02],
    ['border.control', 'surface.sunken', 'ui', 'light', 4.34],
    ['canvas.edge-active', 'canvas.bg', 'ui', 'light', 3.15],
    ['canvas.selection', 'surface.default', 'ui', 'light', 3.3],
    ['fg.default', 'surface.sunken', 'text', 'dark', 19.28],
    ['action.danger.fg', 'action.danger.bg', 'text', 'dark', 6.45],
    ['border.control', 'surface.raised', 'ui', 'dark', 3.07],
    ['canvas.edge-active', 'canvas.bg', 'ui', 'dark', 8.26],
  ];

  it.each(expected)('%s on %s (%s, %s) is %f', (fg, bg, _kind, theme, value) => {
    const values = colorValues(theme);
    expect(ratio(values[fg] as string, values[bg] as string)).toBeCloseTo(value, 2);
  });
});

describe('the contrast check rejects bad pairs', () => {
  const values = { 'a.fg': '#777777', 'a.bg': '#888888', 'b.fg': '#000000', 'b.bg': '#FFFFFF' };

  it('rejects a synthetic pair below the minimum', () => {
    const failing: Pair = { fg: 'a.fg', bg: 'a.bg', kind: 'text', min: 4.5 };
    expect(evaluatePairs([failing], values)).toHaveLength(1);
  });

  it('rejects a lowered minimum even when the ratio would pass it', () => {
    const lowered: Pair = { fg: 'a.fg', bg: 'a.bg', kind: 'text', min: 1 };
    expect(evaluatePairs([lowered], values).length).toBeGreaterThan(0);
  });

  it('accepts a passing pair', () => {
    expect(evaluatePairs([{ fg: 'b.fg', bg: 'b.bg', kind: 'text', min: 4.5 }], values)).toEqual([]);
  });

  it('rejects an exempt pair without a reason and an unknown token', () => {
    expect(evaluatePairs([{ fg: 'a.fg', bg: 'a.bg', kind: 'decorative' }], values)).toHaveLength(1);
    expect(evaluatePairs([{ fg: 'missing', bg: 'a.bg', kind: 'text', min: 4.5 }], values)).toHaveLength(1);
  });
});

describe('contrast report', () => {
  it('is written from the declared pairs', () => {
    const light = colorValues('light');
    const dark = colorValues('dark');
    // A translucent color (8 digits) has no single ratio; its pair is decorative and shows a dash.
    const fmt = (values: Record<string, string>, pair: Pair) =>
      /^#[0-9a-f]{6}$/i.test(values[pair.fg] as string) && /^#[0-9a-f]{6}$/i.test(values[pair.bg] as string)
        ? ratio(values[pair.fg] as string, values[pair.bg] as string).toFixed(2)
        : '-';
    const rows = pairs.map((pair) => {
      const min = pair.kind === 'text' || pair.kind === 'ui' ? pair.min?.toFixed(1) : '-';
      const result = pair.kind === 'text' || pair.kind === 'ui' ? 'pass' : `exempt: ${pair.reason}`;
      return `| \`${pair.fg}\` | \`${pair.bg}\` | ${pair.kind} | ${min} | ${fmt(light, pair)} | ${fmt(dark, pair)} | ${result} |`;
    });
    const exempt = pairs.length - certified.length;
    const report = `<!-- SPDX-FileCopyrightText: The Orcon Authors -->
<!-- SPDX-License-Identifier: Apache-2.0 -->

# Contrast report

Status: Generated — do not edit by hand

This file is generated by the \`@orcon/tokens\` tests (\`pnpm --filter @orcon/tokens test\`, \`test/contrast.test.ts\`) from \`src/pairs.json\`. Ratios use the WCAG 2.x relative luminance formula. Minimums are ${MINIMUM.text}:1 for text and ${MINIMUM.ui}:1 for UI components; the large-text reduction is not used. CI fails when this file is not current. After the test rewrites it, commit it and re-project the skill with \`sh .agents/skills/orcon-ui/scripts/project.sh\`.

Declared pairs: ${pairs.length}. Certified text and UI pairs per theme: ${certified.length}. Exempt pairs (decorative or disabled): ${exempt}. Failures: 0.

| Foreground | Background | Kind | Min | Light | Dark | Result |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
    mkdirSync(dirname(reportPath), { recursive: true });
    writeFileSync(reportPath, report);
    expect(report).toContain('Failures: 0.');
  });
});
